create table if not exists public.madic_cric_invoices (
 id uuid primary key default gen_random_uuid(),
 space_id uuid not null references public.madic_cric_spaces(id),
 client_id uuid not null references auth.users(id),
 dossier_id uuid references public.dossiers(id),
 invoice_number text not null,
 issued_on date not null default current_date,
 due_on date,
 description text not null,
 currency text not null default 'CAD' check (currency='CAD'),
 amount_cents bigint not null check(amount_cents>=0),
 tax_rate numeric(6,4) not null default 0 check(tax_rate>=0 and tax_rate<=1),
 paid_cents bigint not null default 0 check(paid_cents>=0),
 status text not null default 'draft' check(status in ('draft','issued','cancelled')),
 cabinet_name text not null,
 cabinet_address text,
 cabinet_tax_numbers text,
 notes text,
 created_at timestamptz not null default now(),
 unique(space_id,invoice_number),
 check (paid_cents <= round(amount_cents*(1+tax_rate))::bigint)
);
create index if not exists madic_cric_invoices_space_idx on public.madic_cric_invoices(space_id,issued_on desc);
create or replace function public.madic_invoice_space_allowed(p_space uuid, p_client uuid, p_dossier uuid)
returns boolean language sql stable security invoker set search_path = public as $$
 select coalesce(public.madic_can_manage_cric_space(p_space),false)
 and exists(select 1 from public.madic_cric_clients cc where cc.space_id=p_space and cc.client_id=p_client)
 and (p_dossier is null or exists(select 1 from public.dossiers d where d.id=p_dossier and d.space_id=p_space and d.client_id=p_client));
$$;
revoke all on function public.madic_invoice_space_allowed(uuid,uuid,uuid) from public;
grant execute on function public.madic_invoice_space_allowed(uuid,uuid,uuid) to authenticated;
alter table public.madic_cric_invoices enable row level security;
-- This table has NO policy granting MADIC superadmin cross-cabinet access.
create policy madic_invoice_select_cric on public.madic_cric_invoices for select to authenticated
 using (public.madic_invoice_space_allowed(space_id,client_id,dossier_id));
create policy madic_invoice_insert_cric on public.madic_cric_invoices for insert to authenticated
 with check (public.madic_invoice_space_allowed(space_id,client_id,dossier_id));
create policy madic_invoice_update_cric on public.madic_cric_invoices for update to authenticated
 using (public.madic_invoice_space_allowed(space_id,client_id,dossier_id))
 with check (public.madic_invoice_space_allowed(space_id,client_id,dossier_id));
revoke all on public.madic_cric_invoices from anon;
grant select,insert,update on public.madic_cric_invoices to authenticated;
-- Note: Invoice numbers are generated by the database, scoped to each cabinet.
create table if not exists public.madic_cric_invoice_sequences (
 space_id uuid primary key references public.madic_cric_spaces(id),
 next_number bigint not null default 1
);
alter table public.madic_cric_invoice_sequences enable row level security;
revoke all on public.madic_cric_invoice_sequences from anon,authenticated;
create or replace function public.madic_create_cric_invoice(
 p_space_id uuid,p_client_id uuid,p_dossier_id uuid,p_description text,
 p_amount_cents bigint,p_tax_rate numeric,p_due_on date,p_cabinet_name text,
 p_cabinet_address text default null,p_cabinet_tax_numbers text default null,p_notes text default null)
returns uuid language plpgsql security definer set search_path = public as $$
declare n bigint; result uuid;
begin
 if auth.uid() is null or not public.madic_invoice_space_allowed(p_space_id,p_client_id,p_dossier_id) then raise exception 'Accès refusé'; end if;
 if length(trim(coalesce(p_description,'')))=0 or length(trim(coalesce(p_cabinet_name,'')))=0 or p_amount_cents<0 or p_tax_rate<0 or p_tax_rate>1 then raise exception 'Paramètres invalides'; end if;
 insert into public.madic_cric_invoice_sequences(space_id,next_number) values(p_space_id,2)
 on conflict(space_id) do update set next_number=public.madic_cric_invoice_sequences.next_number+1
 returning next_number-1 into n;
 insert into public.madic_cric_invoices(space_id,client_id,dossier_id,invoice_number,description,amount_cents,tax_rate,due_on,cabinet_name,cabinet_address,cabinet_tax_numbers,notes)
 values(p_space_id,p_client_id,p_dossier_id,'FAC-'||extract(year from current_date)::text||'-'||lpad(n::text,5,'0'),trim(p_description),p_amount_cents,p_tax_rate,p_due_on,trim(p_cabinet_name),p_cabinet_address,p_cabinet_tax_numbers,p_notes)
 returning id into result;
 return result;
end $$;
revoke all on function public.madic_create_cric_invoice(uuid,uuid,uuid,text,bigint,numeric,date,text,text,text,text) from public;
grant execute on function public.madic_create_cric_invoice(uuid,uuid,uuid,text,bigint,numeric,date,text,text,text,text) to authenticated;
